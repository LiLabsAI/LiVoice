import { clipboard, type Data } from 'electron'
import { execFile } from 'child_process'

const PASTE_SETTLE_MS = 80
const PASTE_AFTER_MS = 220
const APPLESCRIPT_TIMEOUT_MS = 5_000

/**
 * Inserts text at the focused app's cursor: clipboard snapshot → transient write →
 * native CGEventPost ⌘V (with osascript fallback) → non-destructive restore.
 * Only restores the previous clipboard if our pasted text is still on it, so we
 * never clobber something the user copied during the paste window.
 */
export async function pasteText(
  text: string,
  validate: () => Promise<boolean>,
  nativePaste?: () => Promise<boolean>
): Promise<void> {
  if (text.trim().length === 0) return
  if (!(await validate())) throw new Error('EDITOR_CHANGED')

  const previous = snapshotClipboard()

  clipboard.writeText(text)
  try {
    // Signal macOS clipboard managers (Raycast, Maccy, Paste, 1Password, etc.)
    // to ignore transient dictated text. Guard against writeBuffer clearing text.
    clipboard.writeBuffer('org.nspasteboard.TransientType', Buffer.alloc(0))
    clipboard.writeBuffer('org.nspasteboard.AutoGeneratedType', Buffer.alloc(0))
    if (clipboard.readText() !== text) clipboard.writeText(text)
  } catch {
    clipboard.writeText(text)
  }

  try {
    await sleep(PASTE_SETTLE_MS)
    if (!(await validate())) throw new Error('EDITOR_CHANGED')

    let pasted = false
    if (nativePaste !== undefined) {
      try {
        pasted = await nativePaste()
      } catch {
        pasted = false
      }
    }
    if (!pasted) {
      await pasteWithAppleScript()
    }
    await sleep(PASTE_AFTER_MS)
  } finally {
    // Only restore if the clipboard still holds our dictated text (don't clobber
    // something the user copied while paste was running).
    if (clipboard.readText() === text) {
      restoreClipboard(previous)
    }
  }
}

function snapshotClipboard(): Data {
  const formats = clipboard.availableFormats()
  const snapshot: Data = {}
  const text = clipboard.readText()
  if (text.length > 0) snapshot.text = text
  if (formats.includes('text/html')) {
    const html = clipboard.readHTML()
    if (html.length > 0) snapshot.html = html
  }
  if (formats.includes('text/rtf')) {
    const rtf = clipboard.readRTF()
    if (rtf.length > 0) snapshot.rtf = rtf
  }
  if (formats.some((format) => format.startsWith('image/'))) {
    const image = clipboard.readImage()
    if (!image.isEmpty()) snapshot.image = image
  }
  return snapshot
}

function restoreClipboard(snapshot: Data): void {
  if (
    snapshot.text !== undefined ||
    snapshot.html !== undefined ||
    snapshot.rtf !== undefined ||
    snapshot.image !== undefined
  ) {
    clipboard.write(snapshot)
  } else {
    clipboard.clear()
  }
}

function pasteWithAppleScript(): Promise<void> {
  return new Promise<void>((resolve, reject) => {
    execFile(
      'osascript',
      ['-e', 'tell application "System Events" to keystroke "v" using command down'],
      { timeout: APPLESCRIPT_TIMEOUT_MS },
      (error) => (error ? reject(error) : resolve())
    )
  })
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms))
}
